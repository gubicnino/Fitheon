// PreToolUse hook: refuses direct edits to files that must not be hand-edited.
// Reads the tool call as JSON on stdin and prints a deny decision when the path is protected.
import path from 'node:path';

let raw = '';
for await (const chunk of process.stdin) raw += chunk;

let filePath = '';
try {
  filePath = JSON.parse(raw).tool_input?.file_path ?? '';
} catch {
  process.exit(0);
}
if (!filePath) process.exit(0);

const root = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();
const relative = path.relative(root, path.resolve(root, filePath)).replaceAll('\\', '/').toLowerCase();
const base = path.posix.basename(relative);

let reason = null;
if (base === 'package-lock.json') {
  reason = 'package-lock.json is generated. Change dependencies with npm install (or npx expo install in apps/mobile) from the repo root.';
} else if (base.startsWith('.env') && base !== '.env.example') {
  reason = '.env files hold secrets and are not edited by Claude. Ask the owner to change them.';
} else if (/^apps\/mobile\/(ios|android)\//.test(relative)) {
  reason = 'ios/ and android/ are generated by Expo. Configure native behaviour in app.json or a config plugin.';
}

if (reason) {
  console.log(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: 'deny',
      permissionDecisionReason: reason,
    },
  }));
}
